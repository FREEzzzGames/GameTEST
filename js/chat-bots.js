function buildReplies(blueprint){
  const out=[];
  let n=1;
  for(const stem of blueprint.stems){
    for(const tail of blueprint.tails){
      out.push({id:blueprint.id+"_"+String(n++).padStart(3,"0"),text:stem+" "+tail});
    }
  }
  return out;
}

const CHAT_BOTS=BOT_BLUEPRINTS.map(bot=>({...bot,replies:buildReplies(bot)}));

function getAllBotReplies(){
  return CHAT_BOTS.flatMap(bot=>bot.replies.map(reply=>({...reply,botId:bot.id,botName:bot.name,avatar:bot.avatar})));
}

function pickBot(text="",room="main"){
  const value=String(text||"").toLowerCase();
  const weighted=CHAT_BOTS.map(bot=>{
    let score=Math.random();
    if(room==="games"&&bot.id==="arcade")score+=2;
    if(room==="main"&&bot.id==="community")score+=1.5;
    if((/стрим|live|эфир|канал|трансляц/.test(value))&&bot.id==="live")score+=4;
    if((/игр|game|каталог|пазл|аркад/.test(value))&&bot.id==="arcade")score+=3;
    if((/android|телефон|webview|ошиб|код|прилож/.test(value))&&bot.id==="tech")score+=4;
    if((/чат|привет|общени|сообщ/.test(value))&&bot.id==="community")score+=3;
    return {bot,score};
  }).sort((a,b)=>b.score-a.score);
  return weighted[0].bot;
}

function pickReply(bot,usedIds=new Set()){
  const pool=bot.replies.filter(x=>!usedIds.has(x.id));
  const source=pool.length?pool:bot.replies;
  return source[Math.floor(Math.random()*source.length)];
}

export {CHAT_BOTS,getAllBotReplies,pickBot,pickReply};
